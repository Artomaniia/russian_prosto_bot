def start_message(username: str) -> str:
    return (
        f"Привет, {username}! ✨\n\n"
        "Я буду помогать тебе изучать ударения для подготовки к ОГЭ/ЕГЭ "
        "по русскому языку.\n\n"
        "Нажми test, чтобы начать тренировку, или help, чтобы посмотреть справку 🌿"
    )


def random_question_message(word: str) -> str:
    return (
        "Выбери, пожалуйста, вариант, где ударение поставлено верно ✨\n\n"
        f"{word}"
    )


def ege_question_message(lines: list[str]) -> str:
    return (
        "Укажи, пожалуйста, номера слов, в которых ударение поставлено верно 🌿\n"
        "Ответ можно прислать так: 1 3 5 или 135.\n\n"
        + "\n".join(lines)
    )


def success_message(correct_answers: list[str]) -> str:
    return f"✨ Всё правильно!\nПравильный ответ: {', '.join(correct_answers)}"


def fail_message(correct_answers: list[str]) -> str:
    return (
        f"Ничего страшного, такое бывает 🌿\n"
        f"Правильный ответ: {', '.join(correct_answers)}"
    )